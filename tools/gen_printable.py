#!/usr/bin/env python3
"""Writes src/zipfile/printable.mojo: the code point ranges where Python's str.isprintable() is false (Python 3.14,
Unicode 16.0), so repr() of names in error texts matches CPython exactly. Rerun after a Python/Unicode bump."""
import os
import sys
import unicodedata

ranges, start = [], None
for c in range(0x110000):
    np = True if 0xD800 <= c <= 0xDFFF else not chr(c).isprintable()
    if np and start is None:
        start = c
    if not np and start is not None:
        ranges.append((start, c - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))
data = "".join(f"{a:06x}{b:06x}" for a, b in ranges)
chunks = [data[i:i + 96] for i in range(0, len(data), 96)]
body = "\n".join(f'    "{c}"' for c in chunks)
out = f'''"""Generated by tools/gen_printable.py (Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}): the code point
ranges where str.isprintable() is false, start and end as 6 hex digits each. Do not edit."""
from std.builtin.globals import global_constant

comptime _N = {len(ranges)}
comptime _HEX = (
{body}
)


def _digit(c: Int) -> Int:
    return c - 48 if c < 58 else c - 87


def _table() -> Array[UInt32, {2 * len(ranges)}]:
    var t = Array[UInt32, {2 * len(ranges)}](fill=0)
    var b = _HEX.as_bytes()
    for i in range({2 * len(ranges)}):
        var v = 0
        for k in range(6):
            v = v * 16 + _digit(Int(b[i * 6 + k]))
        t[i] = UInt32(v)
    return t^


comptime _TABLE = _table()


def is_printable(c: Int) -> Bool:
    """Python str.isprintable() for one code point."""
    var t = Pointer(to=global_constant[_TABLE]()).unsafe_bitcast[UInt32]()
    var lo = 0
    var hi = _N - 1
    while lo <= hi:
        var mid = (lo + hi) >> 1
        if c < Int(t.unsafe_offset(2 * mid)[]):
            hi = mid - 1
        elif c > Int(t.unsafe_offset(2 * mid + 1)[]):
            lo = mid + 1
        else:
            return False
    return True
'''
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "zipfile", "printable.mojo"), "w").write(out)
